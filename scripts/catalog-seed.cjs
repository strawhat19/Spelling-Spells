const fs = require(`node:fs`);
const path = require(`node:path`);
const crypto = require(`node:crypto`);
const { loadModule } = require(`./catalog-tools.cjs`);

const root = path.resolve(__dirname, `..`);
const sql = (value) => `'${String(value).replace(/'/g, `''`)}'`;
const json = (value) => `${sql(JSON.stringify(value))}::jsonb`;
const sourceIdentity = (url, number) => {
  const hash = crypto.createHash(`sha256`).update(url).digest(`hex`);
  const uuid = `${hash.slice(0, 8)}-${hash.slice(8, 12)}-4${hash.slice(13, 16)}-8${hash.slice(17, 20)}-${hash.slice(20, 32)}`;
  return { number, id: `Source_${number}_Reference_2026-10-21_${uuid}` };
};
const getSeedRecords = () => {
  const { seedSpells, seedWorlds } = loadModule(`src/shared/catalog/seed.ts`);
  const { expansionSpells, expansionWorlds } = loadModule(`src/shared/catalog/expansion.ts`);
  const { getSpellSlug } = loadModule(`src/shared/catalog/routes.ts`);
  const sourceMap = new Map();
  const universes = [...seedWorlds, ...expansionWorlds].map((world, index) => ({
    id: world.id, number: index + 1, name: world.name, slug: world.slug || world.id,
    kind: world.kind || `fictional`, payload: { ...world, kind: world.kind || `fictional`, slug: world.slug || world.id },
  }));
  const spells = [...seedSpells, ...expansionSpells].map((spell) => {
    const sourceIds = spell.sources.map((source) => {
      const url = new URL(source.url);
      if (url.protocol !== `https:` || url.username || url.password) throw new Error(`Seed References Require Public HTTPS URLs`);
      if (!sourceMap.has(source.url)) {
        const identity = sourceIdentity(source.url, sourceMap.size + 1);
        sourceMap.set(source.url, { ...identity, label: source.label, url: source.url, payload: {
          label: source.label, url: source.url, kind: `reference`, publisher: url.hostname,
          evidenceNote: `See the entry continuity and source label for the supported scope; importing does not approve publication`,
        } });
      }
      return sourceMap.get(source.url).id;
    });
    const legacy = spell.number <= 9;
    const payload = {
      ...spell, sourceIds, slug: getSpellSlug(spell), casters: spell.casters || [],
      effect: spell.effect || spell.definition,
      entryType: spell.entryType || (spell.number === 2 ? `ability` : [3, 8, 9].includes(spell.number) ? `incantation` : `spell`),
      continuity: spell.continuity || `${spell.sourceTitle} · ${spell.medium} reference scope`,
      evidenceStatus: spell.evidenceStatus || (legacy ? `verified` : `unverified`),
      pronunciationStatus: spell.pronunciationStatus || (spell.pronunciation ? `approximate` : `unavailable`),
    };
    return { id: spell.id, number: spell.number, name: spell.name, slug: payload.slug, universe_id: spell.worldId, payload, legacy };
  });
  const sources = [...sourceMap.values()].sort((left, right) => left.number - right.number);
  for (const [name, records, key] of [[`Spells`, spells, `id`], [`Spell Numbers`, spells, `number`], [`Spell Slugs`, spells, `slug`], [`Universes`, universes, `id`], [`Sources`, sources, `id`], [`Source Numbers`, sources, `number`]]) {
    if (new Set(records.map((record) => record[key])).size !== records.length) throw new Error(`${name} Must Have Unique Stable Identities`);
  }
  return { spells, sources, universes };
};

const buildSeedSql = ({ preserveLegacyPublication = false } = {}) => {
  const { spells, sources, universes } = getSeedRecords();
  const lines = [
    `-- Generated by scripts/catalog-seed.cjs; output only, never executed by the generator.`,
    `-- Applying requires separate approval, the catalog migration, and an explicit session guard:`,
    `-- SET spelling_spells.catalog_import_approved = 'APPROVED_CATALOG_IMPORT';`,
    `-- Expansion entries are always drafts. Existing Owner edits and imported statuses are never overwritten.`,
    `begin;`,
    `set local lock_timeout = '5s';`,
    `set local statement_timeout = '30s';`,
    `do $$ begin if current_setting('spelling_spells.catalog_import_approved', true) is distinct from 'APPROVED_CATALOG_IMPORT' then raise exception 'Catalog Import Requires Explicit Approval'; end if; end; $$;`,
    `create temporary table catalog_seed_accepted (id text primary key) on commit drop;`,
  ];
  for (const row of universes) lines.push(`insert into public.catalog_universes (id, number, slug, name, kind, payload) values (${sql(row.id)}, ${row.number}, ${sql(row.slug)}, ${sql(row.name)}, ${sql(row.kind)}, ${json(row.payload)}) on conflict (id) do nothing;`);
  for (const row of sources) lines.push(`insert into public.catalog_sources (id, number, label, url, payload) values (${sql(row.id)}, ${row.number}, ${sql(row.label)}, ${sql(row.url)}, ${json(row.payload)}) on conflict (id) do nothing;`);
  for (const row of spells) {
    const status = row.legacy && preserveLegacyPublication ? `published` : `draft`;
    lines.push(`with accepted as (insert into public.catalog_spells (id, number, slug, name, universe_id, status, payload) values (${sql(row.id)}, ${row.number}, ${sql(row.slug)}, ${sql(row.name)}, ${sql(row.universe_id)}, ${sql(status)}, ${json(row.payload)}) on conflict (id) do update set universe_id = excluded.universe_id, name = excluded.name, payload = excluded.payload, status = excluded.status, revision = public.catalog_spells.revision + 1, updated_at = clock_timestamp() where public.catalog_spells.payload ->> 'seedPlaceholder' = 'true' and public.catalog_spells.number = excluded.number and public.catalog_spells.slug = excluded.slug returning id) insert into catalog_seed_accepted (id) select id from accepted;`);
    for (const sourceId of row.payload.sourceIds) lines.push(`insert into public.catalog_spell_sources (spell_id, source_id) select ${sql(row.id)}, ${sql(sourceId)} where exists (select 1 from catalog_seed_accepted where id = ${sql(row.id)}) on conflict (spell_id, source_id) do nothing;`);
  }
  for (const table of [`catalog_spells`, `catalog_universes`, `catalog_sources`]) lines.push(`update app_private.counters set number = greatest(number, coalesce((select max(number) from public.${table}), 0)) where name = ${sql(table)};`);
  lines.push(`commit;`, ``);
  return lines.join(`\n`);
};

const main = () => {
  const args = process.argv.slice(2);
  if (args.includes(`--help`)) {
    console.log(`node scripts/catalog-seed.cjs [--preserve-legacy-publication] [--output relative-file.sql]\nGenerates SQL only. Default: all entries draft. The explicit legacy option publishes only the nine original records while first replacing untouched placeholders; later imports preserve all edits/statuses. No database, Auth, DNS, billing or deployment operation runs.`);
    return;
  }
  let output = `supabase/generated/catalog-seed.sql`;
  let preserveLegacyPublication = false;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === `--preserve-legacy-publication`) preserveLegacyPublication = true;
    else if (args[index] === `--output` && args[index + 1]) output = args[++index];
    else throw new Error(`Unsupported Seed Argument: ${args[index]}`);
  }
  const filename = path.resolve(root, output);
  if (!filename.startsWith(`${root}${path.sep}`) || !filename.endsWith(`.sql`)) throw new Error(`Seed Output Must Be A SQL File Inside This Project`);
  const value = buildSeedSql({ preserveLegacyPublication });
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  fs.writeFileSync(filename, value);
  const records = getSeedRecords();
  console.log(`Generated ${records.spells.length} Entries, ${records.universes.length} Universes And ${records.sources.length} Sources: ${path.relative(root, filename)}`);
  console.log(`No Database Changes Applied. ${preserveLegacyPublication ? `Nine Legacy Records May Retain Publication; Expansion Remains Draft` : `All Imported Entries Remain Draft`}`);
};

module.exports = { getSeedRecords, buildSeedSql };
if (require.main === module) { try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; } }
